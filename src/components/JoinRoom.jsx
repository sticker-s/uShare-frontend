import { useState, useEffect, useRef } from "react";
import { apiFetch } from "../api/client";
import { saveAuthData } from "../utils/storage";

export default function JoinRoom({ onJoined, onCancel }) {
  const [pairingCode, setPairingCode] = useState("");
  const [deviceName, setDeviceName] = useState("");
  const [error, setError] = useState("");
  const [status, setStatus] = useState("idle");
  const [requestId, setRequestId] = useState(null);

  const pollingRef = useRef(null);

  const handleSubmit = async (e) => {
    e.preventDefault();
    setError("");
    setStatus("waiting");

    try {
      const res = await apiFetch("/pairing/request", {
        method: "POST",
        body: JSON.stringify({
          code: pairingCode.trim(),
          deviceName: deviceName.trim(),
        }),
      });
      setRequestId(res.requestId);
    } catch (error) {
      setError(error.message);
      setStatus("idle");
    }
  };

  useEffect(() => {
    if (!requestId || status !== "waiting") return;

    pollingRef.current = setInterval(async () => {
      try {
        const res = await apiFetch(`/pairing/status/${requestId}`);

        if (res.status === "approved") {
          clearInterval(pollingRef.current);
          setStatus("approved");
          saveAuthData(res.deviceToken, res.roomId, deviceName, "member");
          if (onJoined) onJoined();
        } else if (res.status === "rejected") {
          clearInterval(pollingRef.current);
          setStatus("rejected");
          setError("Not welcomed !");
        }
      } catch (error) {
        clearInterval(pollingRef.current);
        setError(error.message);
        setStatus("idle");
      }
    }, 2000);

    return () => clearInterval(pollingRef.current);
  }, [requestId, status, onJoined, deviceName]);

  return (
    <div>
      <div style={{ marginBottom: "1rem" }}>
        <h2 className="card-title">Join an Existing Room</h2>
        <p className="card-subtitle">Enter the 6-digit pairing code generated by the room owner.</p>
      </div>

      {error && <p className="alert-error">{error}</p>}

      {status === "idle" && (
        <form onSubmit={handleSubmit} className="form-grid">
          <div className="field">
            <label htmlFor="pairing-code">6-Digit Pairing Code</label>
            <input
              id="pairing-code"
              className="mono code-input"
              type="text"
              maxLength="6"
              value={pairingCode}
              onChange={(e) => setPairingCode(e.target.value)}
              placeholder="123456"
              required
            />
          </div>

          <div className="field">
            <label htmlFor="join-device">Your Device Name</label>
            <input
              id="join-device"
              type="text"
              value={deviceName}
              onChange={(e) => setDeviceName(e.target.value)}
              placeholder="e.g. John Wick's iPad"
              required
            />
          </div>

          <div className="btn-group">
            <button type="submit" className="btn btn-primary" style={{ flex: 1 }}>
              Request Access
            </button>
            {onCancel && (
              <button type="button" className="btn btn-secondary" onClick={onCancel}>
                Back
              </button>
            )}
          </div>
        </form>
      )}

      {status === "waiting" && (
        <div className="empty-state">
          <p style={{ color: "var(--text)", fontWeight: 500, marginBottom: "0.35rem" }}>
            Waiting for owner approval...
          </p>
          <p style={{ marginBottom: "1rem" }}>Keep this screen open while your request is reviewed.</p>
          <button
            type="button"
            className="btn btn-secondary"
            onClick={() => {
              clearInterval(pollingRef.current);
              setStatus("idle");
              setRequestId(null);
            }}
          >
            Cancel Request
          </button>
        </div>
      )}

      {status === "rejected" && (
        <div className="empty-state">
          <button
            type="button"
            className="btn btn-secondary"
            onClick={() => {
              setStatus("idle");
              setRequestId(null);
              setError("");
            }}
          >
            Try Again
          </button>
        </div>
      )}
    </div>
  );
}
